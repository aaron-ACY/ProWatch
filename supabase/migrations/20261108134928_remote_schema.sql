CREATE FUNCTION public.check_risk_alert()
  RETURNS TRIGGER
  LANGUAGE plpgsql
  SECURITY DEFINER
  SET search_path TO ''
  AS $function$
BEGIN
  IF new.risk_score >= 0.85 THEN
    INSERT INTO public.risk_alerts (user_id, reading_id, alert_level, message)
    VALUES (new.user_id, new.id, 'critical', 'Risk score rất cao: ' || round(new.risk_score * 100) || '%');
  ELSIF new.risk_score >= 0.6 THEN
    INSERT INTO public.risk_alerts (user_id, reading_id, alert_level, message)
    VALUES (new.user_id, new.id, 'warning', 'Risk score cao: ' || round(new.risk_score * 100) || '%');
  END IF;
  RETURN new;
END;
$function$;

