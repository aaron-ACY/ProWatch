-- ==============================================================================
-- TÁCH BẢNG ACTIVITIES VÀ CẬP NHẬT HEALTH_RECORDS TRÊN SUPABASE
-- ==============================================================================

-- 1. Tạo bảng activities mới lưu trữ thông tin vận động và cảm biến gia tốc MPU6050
CREATE TABLE IF NOT EXISTS public.activities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id TEXT REFERENCES public.devices(device_id) ON DELETE SET NULL,
    user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE,
    activity TEXT DEFAULT 'Đứng yên',
    steps INTEGER DEFAULT 0 CHECK (steps IS NULL OR steps >= 0),
    calories NUMERIC(8,2) DEFAULT 0 CHECK (calories IS NULL OR calories >= 0),
    accel_x DOUBLE PRECISION,
    accel_y DOUBLE PRECISION,
    accel_z DOUBLE PRECISION,
    offline_seq BIGINT,
    recorded_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Thêm chú thích cho các cột
COMMENT ON TABLE public.activities IS 'Bảng ghi nhận hoạt động vận động và cảm biến MPU6050';
COMMENT ON COLUMN public.activities.activity IS 'Phân loại hoạt động: đi bộ, chạy, leo cầu thang, đứng yên, nghỉ ngơi,...';
COMMENT ON COLUMN public.activities.steps IS 'Số bước chân tích lũy';
COMMENT ON COLUMN public.activities.calories IS 'Lượng calo tiêu thụ (kcal)';
COMMENT ON COLUMN public.activities.accel_x IS 'Gia tốc trục X từ MPU6050 (g hoặc m/s^2)';
COMMENT ON COLUMN public.activities.accel_y IS 'Gia tốc trục Y từ MPU6050 (g hoặc m/s^2)';
COMMENT ON COLUMN public.activities.accel_z IS 'Gia tốc trục Z từ MPU6050 (g hoặc m/s^2)';

-- 2. Chỉ mục tối ưu truy vấn
CREATE INDEX IF NOT EXISTS idx_activities_user_time ON public.activities (user_id, recorded_at DESC);
CREATE INDEX IF NOT EXISTS idx_activities_device_time ON public.activities (device_id, recorded_at DESC);
CREATE INDEX IF NOT EXISTS idx_activities_activity ON public.activities (activity);
CREATE UNIQUE INDEX IF NOT EXISTS idx_activities_device_seq 
    ON public.activities (device_id, offline_seq) 
    WHERE offline_seq IS NOT NULL;

-- 3. Di chuyển dữ liệu hoạt động hiện có từ health_records sang activities
INSERT INTO public.activities (device_id, user_id, steps, calories, activity, offline_seq, recorded_at)
SELECT device_id, user_id, steps, calories, COALESCE(activity, 'Đo chủ động'), offline_seq, recorded_at
FROM public.health_records
WHERE (steps IS NOT NULL AND steps > 0)
   OR (calories IS NOT NULL AND calories > 0)
   OR (activity IS NOT NULL);

-- 4. Bỏ các cột steps, calories, activity khỏi bảng health_records
ALTER TABLE public.health_records DROP COLUMN IF EXISTS steps CASCADE;
ALTER TABLE public.health_records DROP COLUMN IF EXISTS calories CASCADE;
ALTER TABLE public.health_records DROP COLUMN IF EXISTS activity CASCADE;

-- 5. Thiết lập bảo mật Row Level Security (RLS) cho activities
ALTER TABLE public.activities ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Users can view own activities" ON public.activities;
CREATE POLICY "Users can view own activities" 
    ON public.activities FOR SELECT 
    USING (user_id IS NULL OR user_id = (SELECT auth.uid()));

DROP POLICY IF EXISTS "Users or services can insert activities" ON public.activities;
CREATE POLICY "Users or services can insert activities" 
    ON public.activities FOR INSERT 
    WITH CHECK (user_id IS NULL OR user_id = (SELECT auth.uid()));

DROP POLICY IF EXISTS "Users can update own activities" ON public.activities;
CREATE POLICY "Users can update own activities" 
    ON public.activities FOR UPDATE 
    USING (user_id IS NULL OR user_id = (SELECT auth.uid()))
    WITH CHECK (user_id IS NULL OR user_id = (SELECT auth.uid()));

DROP POLICY IF EXISTS "Users can delete own activities" ON public.activities;
CREATE POLICY "Users can delete own activities" 
    ON public.activities FOR DELETE 
    USING (user_id IS NULL OR user_id = (SELECT auth.uid()));

-- 6. Phân quyền bảng cho các role Supabase
GRANT ALL ON TABLE public.activities TO anon, authenticated, service_role;

-- 7. Kích hoạt Realtime cho bảng activities
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_publication_tables 
        WHERE pubname = 'supabase_realtime' 
        AND schemaname = 'public' 
        AND tablename = 'activities'
    ) THEN
        ALTER PUBLICATION supabase_realtime ADD TABLE public.activities;
    END IF;
END $$;

